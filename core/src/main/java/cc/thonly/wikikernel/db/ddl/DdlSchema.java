package cc.thonly.wikikernel.db.ddl;

import cc.thonly.wikikernel.common.data.DbType;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.time.Instant;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.Date;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;

/**
 * Auto-DDL 的共享工具：数据库方言（SQLite / MySQL / MariaDB / H2）与列类型映射，
 * 以及「表定义 → {@code CREATE TABLE} / {@code ALTER TABLE ADD COLUMN}」的语句生成。
 * <p>
 * 两个使用方：
 * <ul>
 *     <li>{@link MybatisPlusAutoDdl}：core 自己的 {@code @TableName} 实体（MyBatis-Plus {@code TableInfo} 元数据）；</li>
 *     <li>{@link PluginSchemaDdl}：插件通过 {@code WikiPlugin.schemaEntities()} 声明的实体（反射元数据）。</li>
 * </ul>
 * 只增不减：不会删列、不会改类型、不会动索引（与 JPA 的 {@code ddl-auto=update} 一样保守）。
 */
public final class DdlSchema {

    private static final Logger log = LoggerFactory.getLogger(DdlSchema.class);

    private DdlSchema() {
    }

    // ==================== 表定义模型 ====================

    /** 一张表的结构（与 MyBatis-Plus / 插件实体无关的中间模型）。 */
    public record Table(String name, String primaryKey, List<Column> columns) {
    }

    /** 一列的结构。{@code javaType} 只在 {@link DbType#AUTO} 时用于推断列类型。 */
    public record Column(String name,
                         Class<?> javaType,
                         DbType dbType,
                         int length,
                         int precision,
                         int scale,
                         boolean notNull,
                         String defaultValue,
                         boolean unique,
                         String comment,
                         boolean identity) {

        /** 常用字段的简版（AUTO 类型、可空、无默认值）。 */
        public static Column of(String name, Class<?> javaType) {
            return new Column(name, javaType, DbType.AUTO, 0, 19, 4, false, "", false, "", false);
        }
    }

    /** 需要执行的补列语句 + 列名 + 给调用方记日志的提示（可空）。 */
    public record Alter(String column, String sql, String note) {
    }

    // ==================== 方言 ====================

    /** 不同数据库的类型差异集中在这里。 */
    public enum Dialect {
        SQLITE, MYSQL, H2, OTHER;

        public static Dialect from(String productName) {
            String name = productName == null ? "" : productName.toLowerCase(Locale.ROOT);
            if (name.contains("sqlite")) {
                return SQLITE;
            }
            if (name.contains("mysql") || name.contains("mariadb")) {
                return MYSQL;
            }
            if (name.contains("h2")) {
                return H2;
            }
            return OTHER;
        }

        String booleanType() {
            return switch (this) {
                case MYSQL -> "TINYINT(1)";
                case H2 -> "BOOLEAN";
                default -> "INTEGER";
            };
        }

        String blobType() {
            return this == MYSQL ? "LONGBLOB" : "BLOB";
        }

        /** 超长文本：MySQL LONGTEXT / H2 CLOB / SQLite TEXT。 */
        String longTextType() {
            return switch (this) {
                case MYSQL -> "LONGTEXT";
                case H2 -> "CLOB";
                default -> "TEXT";
            };
        }

        /** LocalDateTime 的列类型（SQLite 存 ISO-8601 文本，驱动原生支持读写）。 */
        String dateTimeType() {
            return switch (this) {
                case MYSQL -> "DATETIME(3)";
                case H2 -> "TIMESTAMP";
                default -> "TEXT";
            };
        }

        /** LocalDate 的列类型。 */
        String dateType() {
            return switch (this) {
                case MYSQL, H2 -> "DATE";
                default -> "TEXT";
            };
        }

        /** LocalTime 的列类型。 */
        String timeType() {
            return switch (this) {
                case MYSQL, H2 -> "TIME";
                default -> "TEXT";
            };
        }

        /** 自增列语法（SQLite 的自增列由 {@link #createTableSql} 特殊处理，这里用不到）。 */
        String identityClause() {
            return switch (this) {
                case MYSQL -> " AUTO_INCREMENT";
                default -> " GENERATED BY DEFAULT AS IDENTITY";
            };
        }
    }

    // ==================== 列类型 ====================

    /** 列的 SQL 类型（{@link DbType#AUTO} 时按 Java 类型推断）。 */
    public static String sqlType(Dialect dialect, Column column) {
        return switch (column.dbType()) {
            case AUTO -> inferSqlType(dialect, column);
            case VARCHAR -> "VARCHAR(" + Math.max(column.length(), 1) + ")";
            case TEXT -> "TEXT";
            case LONGTEXT -> dialect.longTextType();
            case TINYINT -> "TINYINT";
            case SMALLINT -> "SMALLINT";
            case INT -> "INT";
            case BIGINT -> "BIGINT";
            case BOOLEAN -> dialect.booleanType();
            case FLOAT -> "FLOAT";
            case DOUBLE -> "DOUBLE";
            case DECIMAL -> "DECIMAL(" + column.precision() + "," + column.scale() + ")";
            case DATE -> dialect.dateType();
            case TIME -> dialect.timeType();
            case DATETIME -> dialect.dateTimeType();
            case BLOB -> dialect.blobType();
        };
    }

    /** {@link DbType#AUTO} 时按 Java 字段类型推断列类型。 */
    private static String inferSqlType(Dialect dialect, Column column) {
        Class<?> type = column.javaType();
        if (type == null) {
            return "VARCHAR(255)";
        }
        if (type == String.class || type.isEnum()) {
            int length = column.length() > 0 ? column.length() : 255;
            return length > 4000 ? "TEXT" : "VARCHAR(" + length + ")";
        }
        if (type == Integer.class || type == int.class) {
            return "INT";
        }
        if (type == Long.class || type == long.class) {
            return "BIGINT";
        }
        if (type == Short.class || type == short.class) {
            return "SMALLINT";
        }
        if (type == Byte.class || type == byte.class) {
            return "TINYINT";
        }
        if (type == Boolean.class || type == boolean.class) {
            return dialect.booleanType();
        }
        if (type == Double.class || type == double.class) {
            return "DOUBLE";
        }
        if (type == Float.class || type == float.class) {
            return "FLOAT";
        }
        if (type == BigDecimal.class) {
            return "DECIMAL(" + column.precision() + "," + column.scale() + ")";
        }
        if (type == byte[].class) {
            return dialect.blobType();
        }
        if (type == LocalDateTime.class) {
            return dialect.dateTimeType();
        }
        if (type == LocalDate.class) {
            return dialect.dateType();
        }
        if (type == Instant.class || type == Date.class) {
            if (dialect == Dialect.SQLITE) {
                log.warn("Auto-DDL：字段 {} 使用 {}，SQLite JDBC 驱动不支持该类型，"
                        + "建议改用 LocalDateTime 或 Long（epoch millis）", column.name(), type.getSimpleName());
            }
            return dialect.dateTimeType();
        }
        log.warn("Auto-DDL：未知 Java 类型 {}，按 VARCHAR(255) 处理，可用 @DbColumn(type = DbType.XXX) 显式指定",
                type.getName());
        return "VARCHAR(255)";
    }

    // ==================== 语句生成 ====================

    /** {@code CREATE TABLE} 语句（SQLite 的自增主键必须写成 {@code INTEGER PRIMARY KEY AUTOINCREMENT}）。 */
    public static String createTableSql(Dialect dialect, Table table) {
        List<String> definitions = new ArrayList<>();
        boolean primaryKeyInline = false;
        for (Column column : table.columns()) {
            if (column.identity() && dialect == Dialect.SQLITE) {
                definitions.add(column.name() + " INTEGER PRIMARY KEY AUTOINCREMENT");
                primaryKeyInline = true;
            } else {
                definitions.add(columnDefinition(dialect, column));
            }
        }
        if (table.primaryKey() != null && !primaryKeyInline) {
            definitions.add("PRIMARY KEY (" + columnName(dialect, table.primaryKey()) + ")");
        }
        String sql = "CREATE TABLE " + table.name() + " (" + String.join(", ", definitions) + ")";
        // MySQL / MariaDB 的默认字符集可能是 latin1 / utf8mb3。插件里有 emoji 默认值
        // （WikiGift.icon = 🎁）和中文默认值，必须显式使用 utf8mb4，否则会报
        // Invalid default value for 'icon'。
        if (dialect == Dialect.MYSQL) {
            sql += " DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci";
        }
        return sql;
    }

    private static String columnDefinition(Dialect dialect, Column column) {
        StringBuilder definition = new StringBuilder(columnName(dialect, column.name()))
                .append(' ').append(sqlType(dialect, column));
        if (column.identity()) {
            definition.append(dialect.identityClause());
        } else if (column.notNull()) {
            definition.append(" NOT NULL");
        }
        if (!column.defaultValue().isBlank()) {
            definition.append(" DEFAULT ").append(defaultSql(column));
        }
        if (column.unique()) {
            definition.append(" UNIQUE");
        }
        return definition.toString();
    }

    /**
     * 列名引用：MySQL / MariaDB 统一用反引号，避免 {@code read}、{@code year} 等保留字冲突；
     * SQLite / H2 保持不加引号，避免 H2 把带引号的小写列名当成大小写敏感标识符。
     */
    private static String columnName(Dialect dialect, String name) {
        if (dialect == Dialect.MYSQL) {
            return "`" + name.replace("`", "``") + "`";
        }
        return name;
    }

    /**
     * DEFAULT 字面量：字符串 / 枚举列必须加引号。
     * <p>
     * 例如 {@code WikiFile.license} 的默认值是「共用领域协议」；SQLite 能容忍裸字符串，
     * 但 MySQL / MariaDB 会把它当成标识符，在 {@code CREATE TABLE ... DEFAULT 共用领域协议}
     * 处直接报 1064。数值 / 布尔默认值（{@code 0}、{@code TRUE}）保持不引号；
     * 已经写成 {@code '🎁'} 的默认值保持原样。
     */
    private static String defaultSql(Column column) {
        String value = column.defaultValue().trim();
        if (value.isEmpty()) {
            return value;
        }
        if (!isStringColumn(column) || isQuotedLiteral(value)) {
            return value;
        }
        return "'" + value.replace("'", "''") + "'";
    }

    private static boolean isStringColumn(Column column) {
        Class<?> type = column.javaType();
        if (type == String.class || (type != null && type.isEnum())) {
            return true;
        }
        return column.dbType() == DbType.VARCHAR
                || column.dbType() == DbType.TEXT
                || column.dbType() == DbType.LONGTEXT;
    }

    private static boolean isQuotedLiteral(String value) {
        return value.length() >= 2 && value.startsWith("'") && value.endsWith("'");
    }

    /**
     * 给已有表补缺失的列（只增不减；不会改类型 / 删列）。
     * SQLite 不允许给已有表直接加 {@code NOT NULL} 且无默认值的列，这类列按可空添加并在 {@code note} 里提示。
     *
     * @param existing 已存在的列名（小写）
     */
    public static List<Alter> addColumnSql(Dialect dialect, Table table, String actualTableName,
                                           Set<String> existing) {
        List<Alter> alters = new ArrayList<>();
        for (Column column : table.columns()) {
            if (existing.contains(column.name().toLowerCase(Locale.ROOT))) {
                continue;
            }
            StringBuilder sql = new StringBuilder("ALTER TABLE ").append(actualTableName)
                    .append(" ADD COLUMN ").append(columnName(dialect, column.name()))
                    .append(' ').append(sqlType(dialect, column));
            String note = null;
            if (!column.defaultValue().isBlank()) {
                sql.append(" DEFAULT ").append(defaultSql(column));
                if (column.notNull()) {
                    sql.append(" NOT NULL");
                }
            } else if (column.notNull()) {
                note = table.name() + "." + column.name() + " 要求 NOT NULL 但没有默认值，按可空列添加";
            }
            alters.add(new Alter(column.name(), sql.toString(), note));
        }
        return alters;
    }

    /** 执行一条 DDL（调用方负责日志与异常处理）。 */
    public static void execute(Connection connection, String sql) throws SQLException {
        try (Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    // ==================== JDBC 元数据 ====================

    /**
     * 数据库里已有的表：小写表名 → 实际表名。
     * <p>
     * 必须限定当前 catalog / schema：MySQL 的 {@code getTables(null, null, "%", ...)}
     * 会返回同一实例中**其它数据库**的同名表，导致 Auto-DDL 误以为表已存在而跳过建表。
     */
    public static Map<String, String> existingTables(DatabaseMetaData metaData) throws SQLException {
        Map<String, String> tables = new LinkedHashMap<>();
        String catalog = currentCatalog(metaData);
        String schema = currentSchema(metaData);
        // H2 2.x 的表类型是 BASE TABLE，MySQL/SQLite 是 TABLE
        try (ResultSet resultSet = metaData.getTables(catalog, schema, "%",
                new String[]{"TABLE", "BASE TABLE"})) {
            while (resultSet.next()) {
                String name = resultSet.getString("TABLE_NAME");
                tables.put(name.toLowerCase(Locale.ROOT), name);
            }
        }
        return tables;
    }

    /** 已有表的列名（小写）。同样限定当前 catalog / schema。 */
    public static Set<String> existingColumns(DatabaseMetaData metaData, String tableName) throws SQLException {
        Set<String> columns = new HashSet<>();
        try (ResultSet resultSet = metaData.getColumns(currentCatalog(metaData),
                currentSchema(metaData), tableName, "%")) {
            while (resultSet.next()) {
                columns.add(resultSet.getString("COLUMN_NAME").toLowerCase(Locale.ROOT));
            }
        }
        return columns;
    }

    private static String currentCatalog(DatabaseMetaData metaData) {
        try {
            return metaData.getConnection().getCatalog();
        } catch (SQLException | RuntimeException ignored) {
            return null;
        }
    }

    private static String currentSchema(DatabaseMetaData metaData) {
        try {
            return metaData.getConnection().getSchema();
        } catch (SQLException | RuntimeException ignored) {
            return null;
        }
    }
}
