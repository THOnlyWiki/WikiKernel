    /** 用户读取替身（真实实现在 core：{@code UserStoreImpl} → {@code UserService} / {@code PermissionService}）。 */
    private final class DatabaseUserStore implements UserStore {

        private final Map<Long, Set<String>> groups = new LinkedHashMap<>();

        @Override
        public Optional<UserRef> byId(long userId) {
            return row("SELECT id, username FROM wiki_user WHERE id = ? LIMIT 1", userId);
        }

        @Override
        public Optional<UserRef> byName(String username) {
            if (username == null || username.isBlank()) {
                return Optional.empty();
            }
            String value = username.trim();
            Optional<UserRef> exact = row("SELECT id, username FROM wiki_user WHERE username = ? LIMIT 1", value);
            if (exact.isPresent()) {
                return exact;
            }
            return row("SELECT id, username FROM wiki_user WHERE LOWER(username) = ? LIMIT 1",
                    value.toLowerCase(java.util.Locale.ROOT));
        }

        @Override
        public Map<Long, String> names(Collection<Long> userIds) {
            if (userIds == null || userIds.isEmpty()) {
                return Map.of();
            }
            String placeholders = String.join(",", Collections.nCopies(userIds.size(), "?"));
            Map<Long, String> result = new LinkedHashMap<>();
            for (DbRow row : new TestDatabase(connection).query(
                    "SELECT id, username FROM wiki_user WHERE id IN (" + placeholders + ")",
                    userIds.toArray())) {
                result.put(row.longValue("id", 0), row.string("username"));
            }
            return result;
        }

        @Override
        public Map<Long, String> avatars(Collection<Long> userIds) {
            return Map.of();
        }

        @Override
        public Set<String> groups(long userId) {
            return groups.getOrDefault(userId, Set.of());
        }

        @Override
        public boolean exists(String username) {
            if (username == null || username.isBlank()) {
                return false;
            }
            try {
                return longValue("SELECT COUNT(*) FROM wiki_user WHERE username = ?", username.trim()) > 0;
            } catch (SQLException exception) {
                throw new IllegalStateException(exception);
            }
        }

        @Override
        public List<UserRef> randomWithAvatar(int limit) {
            return List.of();
        }

        private Optional<UserRef> row(String sql, Object... args) {
            return new TestDatabase(connection).queryOne(sql, args).map(row -> new UserRef(
                    row.longValue("id", 0), row.string("username"), "", false));
        }
    }

    /** 页面查询替身（真实实现在 core：{@code PageQueryStoreImpl} → {@code WikiPageService.getByTitle}）。 */
    private final class H2PageQueryStore implements PageQueryStore {

        @Override
        public List<String> namespaces() {
            return List.of("user", "user-talk");
        }

        @Override
        public Optional<PageDetail> detail(String title) {
            if (title == null || title.isBlank()) {
                return Optional.empty();
            }
            String value = title.trim();
            Optional<PageDetail> exact = row("SELECT id, title, latest_revision_id, protected_page, create_at,"
                    + " update_at FROM wiki_page WHERE title = ? AND deleted = FALSE LIMIT 1", value);
            if (exact.isPresent()) {
                return exact;
            }
            return row("SELECT id, title, latest_revision_id, protected_page, create_at, update_at"
                    + " FROM wiki_page WHERE LOWER(title) = ? AND deleted = FALSE LIMIT 1",
                    value.toLowerCase(java.util.Locale.ROOT));
        }

        @Override
        public List<PageEntry> list(String prefix, String namespace, int limit) {
            return List.of();
        }

        @Override
        public Optional<RevisionEntry> latestRevision(long pageId) {
            return Optional.empty();
        }

        @Override
        public List<RevisionEntry> history(long pageId, int limit) {
            return List.of();
        }

        private Optional<PageDetail> row(String sql, Object... args) {
            return new TestDatabase(connection).queryOne(sql, args).map(row -> new PageDetail(
                    row.longValue("id", 0), row.string("title"), row.longOrNull("latest_revision_id"),
                    row.boolValue("protected_page", false), row.dateTime("create_at"), row.dateTime("update_at")));
        }
    }

    /** 极简 JDBC 版 {@link PluginDatabase}（生产实现是 core 的 PluginDatabaseImpl）。 */
    private record TestDatabase(Connection connection) implements PluginDatabase {

        @Override
        public String databaseProductName() {
            return "H2";
        }

        @Override
        public List<String> tableNames() {
            return List.of();
        }

        @Override
        public int update(String sql, Object... args) {
            try (PreparedStatement statement = connection.prepareStatement(sql)) {
                bind(statement, args);
                return statement.executeUpdate();
            } catch (SQLException exception) {
                throw new IllegalStateException(exception);
            }
        }

        @Override
        public long insert(String sql, Object... args) {
            try (PreparedStatement statement = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
                bind(statement, args);
                statement.executeUpdate();
                try (ResultSet keys = statement.getGeneratedKeys()) {
                    return keys.next() ? keys.getLong(1) : -1;
                }
            } catch (SQLException exception) {
                throw new IllegalStateException(exception);
            }
        }

        @Override
        public List<DbRow> query(String sql, Object... args) {
            try (PreparedStatement statement = connection.prepareStatement(sql)) {
                bind(statement, args);
                try (ResultSet resultSet = statement.executeQuery()) {
                    List<DbRow> rows = new ArrayList<>();
                    ResultSetMetaData meta = resultSet.getMetaData();
                    while (resultSet.next()) {
                        Map<String, Object> values = new LinkedHashMap<>();
                        for (int index = 1; index <= meta.getColumnCount(); index++) {
                            values.put(meta.getColumnLabel(index), resultSet.getObject(index));
                        }
                        rows.add(new DbRow(values));
                    }
                    return rows;
                }
            } catch (SQLException exception) {
                throw new IllegalStateException(exception);
            }
        }

        @Override
        public Optional<DbRow> queryOne(String sql, Object... args) {
            List<DbRow> rows = query(sql, args);
            return rows.isEmpty() ? Optional.empty() : Optional.of(rows.get(0));
        }

        @Override
        public <T> T transaction(Supplier<T> work) {
            return work.get();
        }

        private static void bind(PreparedStatement statement, Object[] args) throws SQLException {
            for (int index = 0; index < args.length; index++) {
                statement.setObject(index + 1, args[index]);
            }
        }
    }
