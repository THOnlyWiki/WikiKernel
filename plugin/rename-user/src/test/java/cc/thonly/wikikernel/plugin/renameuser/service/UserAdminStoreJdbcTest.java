    @BeforeEach
    void setUp() throws SQLException {
        JdbcDataSource dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:rename-user-store-test;DB_CLOSE_DELAY=-1");
        connection = dataSource.getConnection();
        createSchema(connection);
        for (String table : List.of("wiki_user", "wiki_page", "wiki_log")) {
            try (Statement statement = connection.createStatement()) {
                statement.execute("DELETE FROM " + table);
            }
        }
        userStore = new DatabaseUserStore();
        pageStore = new H2PageQueryStore();
        pageCache = new RecordingPageCache();
        logWriter = new RecordingLogWriter();
        store = newStore(true);
    }

    private UserAdminStoreJdbc newStore(boolean capitalizeFirstLetter) {
        return new UserAdminStoreJdbc(new TestDatabase(connection), userStore, pageStore, pageCache,
                logWriter, new RenameUserSupport(RenameUserFakes.pluginMessages()), capitalizeFirstLetter);
    }

    /** 表结构 = 迁移前行读写到的 core 表（H2 方言）。 */
    private static void createSchema(Connection connection) throws SQLException {
        execute(connection, "CREATE TABLE IF NOT EXISTS wiki_user ("
                + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                + "username VARCHAR(255) NOT NULL, password VARCHAR(255) NOT NULL, email CLOB)");
        execute(connection, "CREATE TABLE IF NOT EXISTS wiki_page ("
                + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                + "title VARCHAR(255) NOT NULL, latest_revision_id BIGINT, hided BOOLEAN, deleted BOOLEAN,"
                + "protected_page BOOLEAN, create_at TIMESTAMP, update_at TIMESTAMP)");
        execute(connection, "CREATE TABLE IF NOT EXISTS wiki_log ("
                + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                + "log_type VARCHAR(32) NOT NULL, actor_user_id BIGINT, target VARCHAR(255),"
                + "target_user_id BIGINT, detail VARCHAR(500), hided BOOLEAN, time TIMESTAMP NOT NULL)");
    }

    private static void execute(Connection connection, String sql) throws SQLException {
        try (Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    // ==================== 改名 ====================

    @Test
    void renameValidatesAndUpdatesAccountName() throws SQLException {
        long targetId = insertUser("甲");
        insertUser("乙");
        Viewer actor = Viewer.of(7L, "操作者", Set.of(GROUP_RENAME_USER));

        assertEquals(UserAdminStore.RenameResult.NO_SUCH_USER,
                store.rename(actor, 999L, "甲", "新名", null, false));
        assertEquals(UserAdminStore.RenameResult.SAME_NAME,
                store.rename(actor, targetId, "甲", "甲", null, false));
        assertEquals(UserAdminStore.RenameResult.SAME_NAME,
                store.rename(actor, targetId, "甲", " 甲 ", null, false), "输入按去空白比较");
        assertEquals(UserAdminStore.RenameResult.INVALID_NAME,
                store.rename(actor, targetId, "甲", "非法#名字", null, false));
        assertEquals(UserAdminStore.RenameResult.INVALID_NAME,
                store.rename(actor, targetId, "甲", " ", null, false), "空名非法");
        assertEquals(UserAdminStore.RenameResult.NAME_IN_USE,
                store.rename(actor, targetId, "甲", "乙", null, false));

        assertEquals(UserAdminStore.RenameResult.OK,
                store.rename(actor, targetId, "甲", "新名", "改名理由", false));
        assertEquals("新名", text("SELECT username FROM wiki_user WHERE id = ?", targetId));
        assertTrue(store.byName("新名").isPresent());
        assertEquals("新名", store.byId(targetId).orElseThrow().getUsername());
        assertEquals(1, logWriter.calls.size());
        LogCall call = logWriter.calls.get(0);
        assertEquals("renameuser", call.logType());
        assertEquals(7L, call.actorUserId().longValue());
        assertEquals("甲", call.target(), "日志目标保留旧用户名");
        assertEquals(targetId, call.targetUserId().longValue());
        assertEquals("rename|新名|改名理由", call.detail());
    }

    // ==================== 用户页移动 ====================

    @Test
    void renameMovesUserPagesAndSubpages() throws SQLException {
        long userId = insertUser("甲");
        long mainPage = insertPage("用户:甲");
        long subPage = insertPage("用户:甲/子页面");
        long talkPage = insertPage("用户讨论:甲");
        long otherPage = insertPage("用户:其他人");

        assertEquals(UserAdminStore.RenameResult.OK,
                store.rename(Viewer.of(7L, "操作者", Set.of(GROUP_RENAME_USER)), userId, "甲", "丙", null, true));

        assertEquals(List.of("用户:丙", "用户:丙/子页面", "用户讨论:丙", "用户:其他人"),
                texts("SELECT title FROM wiki_page ORDER BY id"));
        assertNotNull(dateTime("SELECT update_at FROM wiki_page WHERE id = ?", mainPage), "移动会更新 update_at");
        assertEquals(mainPage, longValue("SELECT id FROM wiki_page WHERE title = ?", "用户:丙"));
        assertEquals(subPage, longValue("SELECT id FROM wiki_page WHERE title = ?", "用户:丙/子页面"));
        assertEquals(talkPage, longValue("SELECT id FROM wiki_page WHERE title = ?", "用户讨论:丙"));
        assertEquals(otherPage, longValue("SELECT id FROM wiki_page WHERE title = ?", "用户:其他人"));

        // 移动日志（目标 = 新标题，详情 = 原标题；操作者 = 被改名的账号）+ 改名日志
        assertEquals(List.of("move", "move", "move", "renameuser"),
                logWriter.calls.stream().map(LogCall::logType).toList());
        assertEquals("用户:丙", logWriter.calls.get(0).target());
        assertEquals("用户:甲", logWriter.calls.get(0).detail());
        assertEquals("用户:丙/子页面", logWriter.calls.get(1).target());
        assertEquals("用户:甲/子页面", logWriter.calls.get(1).detail());
        assertEquals("用户讨论:丙", logWriter.calls.get(2).target());
        assertEquals("用户讨论:甲", logWriter.calls.get(2).detail());
        assertEquals(userId, logWriter.calls.get(0).actorUserId().longValue());
        // 页面正文缓存按新标题失效
        assertEquals(List.of("用户:丙", "用户:丙/子页面", "用户讨论:丙"), pageCache.invalidated);
    }

    @Test
    void renameSkipsMoveWhenTargetPageExistsOrMoveNotRequested() throws SQLException {
        long firstId = insertUser("甲");
        insertPage("用户:甲");
        insertPage("用户:丙");
        Viewer actor = Viewer.of(7L, "操作者", Set.of(GROUP_RENAME_USER));

        // 目标页「用户:丙」已被占用 → 跳过移动，但账号改名与日志照常（页用户名 丙 没被占用）
        assertEquals(UserAdminStore.RenameResult.OK, store.rename(actor, firstId, "甲", "丙", null, true));
        assertTrue(store.byName("丙").isPresent());
        assertEquals(List.of("用户:甲", "用户:丙"), texts("SELECT title FROM wiki_page ORDER BY id"),
                "目标页已存在时不移动");
        assertEquals(1, logWriter.calls.size(), "只写改名日志");

        // movePages=false → 完全不动用户页
        long secondId = insertUser("丁");
        insertPage("用户:丁");
        logWriter.calls.clear();
        assertEquals(UserAdminStore.RenameResult.OK, store.rename(actor, secondId, "丁", "戊", null, false));
        assertTrue(texts("SELECT title FROM wiki_page ORDER BY id").contains("用户:丁"));
        assertEquals(1, logWriter.calls.size(), "不勾选时只写改名日志");
    }

    @Test
    void movedUserPageTitleFollowsCoreNormalization() throws SQLException {
        long userId = insertUser("alice");
        insertPage("用户:alice");

        // 默认 wikikernel.title.capitalize-first-letter=true：命名空间后首字符大写
        assertEquals(UserAdminStore.RenameResult.OK,
                store.rename(Viewer.of(7L, "操作者", Set.of(GROUP_RENAME_USER)), userId, "alice", "carol", null, true));
        assertEquals(List.of("用户:Carol"), texts("SELECT title FROM wiki_page ORDER BY id"));

        // 关掉首字母大写（wikikernel.title.capitalize-first-letter=false）时保持原样
        UserAdminStoreJdbc lowerCaseStore = newStore(false);
        long secondId = insertUser("dave");
        insertPage("用户:dave");
        assertEquals(UserAdminStore.RenameResult.OK,
                lowerCaseStore.rename(Viewer.of(7L, "操作者", Set.of(GROUP_RENAME_USER)),
                        secondId, "dave", "erin", null, true));
        assertEquals(List.of("用户:Carol", "用户:erin"), texts("SELECT title FROM wiki_page ORDER BY id"));
    }

    // ==================== 最近的重命名 ====================

    @Test
    void recentRenamesFormatsNewestFirstIncludingHided() throws SQLException {
        long actorId = insertUser("操作者");
        long renamedId = insertUser("新名");
        insertLog("renameuser", actorId, "旧名", renamedId, "rename|新名|乱改", false);
        insertLog("edit", actorId, "页面", null, "摘要", false);
        insertLog("renameuser", actorId, "被隐藏的旧名", null, "rename|隐|", true);
        insertLog("renameuser", actorId, "", renamedId, "rename|再改|", false);

        List<UserAdminStore.RenameLogRow> rows = store.recentRenames(20);
        assertEquals(3, rows.size(), "只取 renameuser 类型，含隐藏日志，新的在前");

        UserAdminStore.RenameLogRow first = rows.get(0);
        assertEquals("操作者", first.actorName());
        assertEquals("新名", first.targetText(), "目标为空时按 target_user_id 解析用户名");
        assertNotNull(first.time());
        assertEquals("重命名用户 ", first.actionBefore());
        assertEquals("", first.actionAfter());
        assertEquals("新用户名：再改", first.detailText());
        assertTrue(first.targetUrl().startsWith("/wiki/"), "目标链接 = 用户页");
        assertTrue(first.targetUrl().contains("%E7%94%A8%E6%88%B7"), "编码后的「用户:」前缀");

        UserAdminStore.RenameLogRow second = rows.get(1);
        assertEquals("被隐藏的旧名", second.targetText(), "renameuser 日志保存的旧用户名优先");
        assertEquals("新用户名：隐", second.detailText());

        UserAdminStore.RenameLogRow third = rows.get(2);
        assertEquals("旧名", third.targetText());
        assertEquals("新用户名：新名，原因：乱改", third.detailText());

        assertEquals(1, store.recentRenames(1).size(), "limit 生效");
        assertEquals(1, store.recentRenames(0).size(), "limit <= 0 时至少 1 条（与迁移前 core 一致）");
    }

