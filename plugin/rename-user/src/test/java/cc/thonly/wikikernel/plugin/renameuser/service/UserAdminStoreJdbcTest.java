/**
 * {@link UserAdminStoreJdbc} 的真实 SQL 回归测试（H2 内存库）：账号改名（校验 / 日志）、
 * 用户页与子页面移动（含目标已占用跳过、标题规范化）与「最近的重命名」格式化都在真数据库上跑一遍
 * （插件测试里的 {@code RenameUserFakes} 是内存替身，覆盖不到 SQL）。
 * <p>
 * 依赖只用 JDBC（测试里自带一个极简的 {@link PluginDatabase} 实现），不需要 core 的 Spring 环境；
 * 用户读取 / 页面查询 / 缓存失效 / 日志写入用桥替身（真实实现在 core）。
 */
