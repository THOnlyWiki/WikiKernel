    // ==================== 工具 ====================

    private long insertUser(String username) throws SQLException {
        try (PreparedStatement statement = connection.prepareStatement(
                "INSERT INTO wiki_user(username, password, email) VALUES (?, 'x', '')")) {
            statement.setString(1, username);
            statement.executeUpdate();
        }
        return longValue("SELECT id FROM wiki_user WHERE username = ?", username);
    }

    private long insertPage(String title) throws SQLException {
        try (PreparedStatement statement = connection.prepareStatement(
                "INSERT INTO wiki_page(title, hided, deleted, protected_page, create_at, update_at)"
                        + " VALUES (?, FALSE, FALSE, FALSE, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)")) {
            statement.setString(1, title);
            statement.executeUpdate();
        }
        return longValue("SELECT id FROM wiki_page WHERE title = ?", title);
    }

    private void insertLog(String logType, Long actorUserId, String target, Long targetUserId,
                           String detail, boolean hided) throws SQLException {
        try (PreparedStatement statement = connection.prepareStatement(
                "INSERT INTO wiki_log(log_type, actor_user_id, target, target_user_id, detail, hided, time)"
                        + " VALUES (?, ?, ?, ?, ?, ?, CURRENT_TIMESTAMP)")) {
            statement.setString(1, logType);
            statement.setObject(2, actorUserId);
            statement.setString(3, target);
            statement.setObject(4, targetUserId);
            statement.setString(5, detail);
            statement.setBoolean(6, hided);
            statement.executeUpdate();
        }
    }

    private long longValue(String sql, Object... args) throws SQLException {
        try (PreparedStatement statement = connection.prepareStatement(sql)) {
            bind(statement, args);
            try (ResultSet resultSet = statement.executeQuery()) {
                return resultSet.next() ? resultSet.getLong(1) : 0;
            }
        }
    }

    private String text(String sql, Object... args) throws SQLException {
        try (PreparedStatement statement = connection.prepareStatement(sql)) {
            bind(statement, args);
            try (ResultSet resultSet = statement.executeQuery()) {
                return resultSet.next() ? resultSet.getString(1) : null;
            }
        }
    }

    private List<String> texts(String sql, Object... args) throws SQLException {
        try (PreparedStatement statement = connection.prepareStatement(sql)) {
            bind(statement, args);
            try (ResultSet resultSet = statement.executeQuery()) {
                List<String> values = new ArrayList<>();
                while (resultSet.next()) {
                    values.add(resultSet.getString(1));
                }
                return values;
            }
        }
    }

    private LocalDateTime dateTime(String sql, Object... args) throws SQLException {
        try (PreparedStatement statement = connection.prepareStatement(sql)) {
            bind(statement, args);
            try (ResultSet resultSet = statement.executeQuery()) {
                if (!resultSet.next()) {
                    return null;
                }
                java.sql.Timestamp timestamp = resultSet.getTimestamp(1);
                return timestamp == null ? null : timestamp.toLocalDateTime();
            }
        }
    }

    private static void bind(PreparedStatement statement, Object[] args) throws SQLException {
        for (int index = 0; index < args.length; index++) {
            statement.setObject(index + 1, args[index]);
        }
    }

