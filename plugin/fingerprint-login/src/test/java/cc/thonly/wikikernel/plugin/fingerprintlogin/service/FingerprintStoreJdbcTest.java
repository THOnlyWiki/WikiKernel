/**
 * {@link FingerprintStoreJdbc} 的真实 SQL 回归测试（H2 内存库）：
 * 插件自有表 {@code wiki_fingerprint} 的建表语句、列名映射与读写路径，以及
 * 「只能删自己的」「每用户上限」「同一摘要更新」「别人的摘要拒绝」四条规则都在真数据库上跑一遍
 * （插件测试里的 {@code FingerprintLoginFakes.MemoryFingerprintStore} 是内存替身，覆盖不到 SQL）。
 * <p>
 * 依赖只用 JDBC（测试里自带一个极简的 {@link PluginDatabase} 实现），不需要 core 的 Spring 环境。
 */
class FingerprintStoreJdbcTest {

    private Connection connection;
    private FingerprintStoreJdbc store;

    @BeforeEach
    void setUp() throws SQLException {
        JdbcDataSource dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:fingerprint-store-test;DB_CLOSE_DELAY=-1");
        connection = dataSource.getConnection();
        createSchema(connection);
        try (Statement statement = connection.createStatement()) {
            statement.execute("DELETE FROM wiki_fingerprint");
        }
        store = new FingerprintStoreJdbc(new TestDatabase(connection));
    }

    /** 表结构 = 插件 {@code schemaEntities()} 声明的 {@code wiki_fingerprint}（H2 方言）。 */
    private static void createSchema(Connection connection) throws SQLException {
        execute(connection, "CREATE TABLE IF NOT EXISTS wiki_fingerprint ("
                + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                + "user_id BIGINT NOT NULL, label VARCHAR(100) DEFAULT '',"
                + "fingerprint_hash VARCHAR(128) NOT NULL UNIQUE, user_agent VARCHAR(300) DEFAULT '',"
                + "created_at TIMESTAMP, last_used_at TIMESTAMP)");
    }

    private static void execute(Connection connection, String sql) throws SQLException {
        try (Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    // ==================== 增删查 ====================

    @Test
    void addFindsAndRemovesOwnFingerprint() {
        long userId = 7L;
        String hash = hash("1");

        WikiFingerprint created = store.add(userId, "我的笔记本 Chrome", hash, "UA/1.0");
        assertNotNull(created.getId());
        assertTrue(created.getId() > 0);
        assertNotNull(created.getCreatedAt(), "登记时间由实现写入");
        assertNull(created.getLastUsedAt(), "还没用过");

        assertEquals(1, store.countByUser(userId));
        assertEquals("我的笔记本 Chrome", store.byHash(hash).orElseThrow().getLabel());
        assertTrue(store.byHash("不存在的摘要").isEmpty());
        assertTrue(store.byHash("   ").isEmpty());
        assertTrue(store.byHash(null).isEmpty());

        // 同一摘要再次登记 = 更新名称 / UA，不新增行
        WikiFingerprint updated = store.add(userId, "公司台式机", hash, "UA/2.0");
        assertEquals(created.getId(), updated.getId());
        assertEquals("公司台式机", updated.getLabel());
        assertEquals("UA/2.0", updated.getUserAgent());
        assertEquals("公司台式机", store.byHash(hash).orElseThrow().getLabel());
        assertEquals(1, store.countByUser(userId));

        // touch 更新 lastUsedAt
        store.touch(created.getId());
        assertNotNull(store.byHash(hash).orElseThrow().getLastUsedAt(), "登录成功后应有最近使用时间");
        store.touch(999_999L);

        // 删除自己的
        assertTrue(store.remove(userId, created.getId()));
        assertFalse(store.remove(userId, created.getId()), "再删返回 false");
        assertTrue(store.byHash(hash).isEmpty());
        assertEquals(0, store.countByUser(userId));
    }

    // ==================== 权限与上限 ====================

    @Test
    void removeOnlyTouchesOwnRowsAndLimitIsPerUser() {
        long mine = 7L;
        long theirs = 8L;
        WikiFingerprint myRow = store.add(mine, "我的", hash("a"), "UA");
        WikiFingerprint theirRow = store.add(theirs, "别人的", hash("b"), "UA");

        assertFalse(store.remove(mine, theirRow.getId()), "不能删别人的指纹");
        assertTrue(store.byHash(hash("b")).isPresent(), "别人的行必须还在");
        assertFalse(store.remove(theirs, 999_999L), "不存在的返回 false");

        // 每用户最多 10 个
        for (int index = 0; index < FingerprintStore.MAX_PER_USER - 1; index++) {
            store.add(mine, "设备" + index, hash("m" + index), "UA");
        }
        assertEquals(FingerprintStore.MAX_PER_USER, store.countByUser(mine));
        assertThrows(IllegalStateException.class,
                () -> store.add(mine, "第十一台", hash("m-limit"), "UA"),
                "超过上限应报错");
        // 别人的额度不受影响
        store.add(theirs, "第二台", hash("b2"), "UA");

        // 别人的摘要不能被抢注
        IllegalArgumentException conflict = assertThrows(IllegalArgumentException.class,
                () -> store.add(mine, "抢注", hash("b"), "UA"));
        assertNotNull(conflict.getMessage());
        assertEquals(theirs, store.byHash(hash("b")).orElseThrow().getUserId(), "归属不变");

        assertEquals(2, store.byUser(theirs).size(), "只列自己的");
        assertTrue(store.byUser(mine).stream()
                .noneMatch(row -> hash("b").equals(row.getFingerprintHash())));
        assertTrue(!myRow.getId().equals(theirRow.getId()));
    }

    // ==================== 入库前的归一化 ====================

    @Test
    void addTruncatesUserAgentAndListsNewestFirst() {
        long userId = 7L;
        WikiFingerprint first = store.add(userId, "第一台", hash("x1"), "u".repeat(400));
        WikiFingerprint second = store.add(userId, "第二台", hash("x2"), "UA/2");

        assertEquals(300, first.getUserAgent().length(), "UA 摘要按列长截断");
        assertEquals(300, store.byHash(hash("x1")).orElseThrow().getUserAgent().length());
        List<WikiFingerprint> rows = store.byUser(userId);
        assertEquals(List.of(second.getId(), first.getId()), rows.stream().map(WikiFingerprint::getId).toList(),
                "最新的排在最前");
        assertTrue(store.byUser(999_999L).isEmpty());
        assertEquals(0, store.countByUser(999_999L));
    }

    @Test
    void addNormalizesHashLabelAndUserAgent() {
        WikiFingerprint row = store.add(7L, "  换行设备  ", "  " + hash("n") + "  ", "  UA  ");
        assertEquals("换行设备", row.getLabel());
        assertEquals("UA", row.getUserAgent());
        assertEquals(hash("n"), row.getFingerprintHash());
        assertTrue(store.byHash(hash("n")).isPresent(), "摘要入库前已 trim");

        // 空 / null 名称与 UA 按空串入库（与迁移前的实现一致）
        WikiFingerprint bare = store.add(8L, null, hash("empty"), null);
        assertEquals("", bare.getLabel());
        assertEquals("", bare.getUserAgent());
        assertEquals("", store.byHash(hash("empty")).orElseThrow().getUserAgent());
    }

    // ==================== 测试替身 ====================

    private static String hash(String seed) {
        StringBuilder builder = new StringBuilder();
        while (builder.length() < 64) {
            builder.append(Integer.toHexString(seed.hashCode() + builder.length()));
        }
        return builder.substring(0, 64);
    }

    /** 极简 JDBC 版 {@link PluginDatabase}（生产实现是 core 的 PluginDatabaseImpl）。 */
    private record TestDatabase(Connection connection) implements PluginDatabase {

        @Override
        public String databaseProductName() {
            return "H2";
        }

        @Override
        public List<String> tableNames() {
            return List.of();
        }

        @Override
        public int update(String sql, Object... args) {
            try (PreparedStatement statement = connection.prepareStatement(sql)) {
                bind(statement, args);
                return statement.executeUpdate();
            } catch (SQLException exception) {
                throw new IllegalStateException(exception);
            }
        }

        @Override
        public long insert(String sql, Object... args) {
            try (PreparedStatement statement = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
                bind(statement, args);
                statement.executeUpdate();
                try (ResultSet keys = statement.getGeneratedKeys()) {
                    return keys.next() ? keys.getLong(1) : -1;
                }
            } catch (SQLException exception) {
                throw new IllegalStateException(exception);
            }
        }

        @Override
        public List<DbRow> query(String sql, Object... args) {
            try (PreparedStatement statement = connection.prepareStatement(sql)) {
                bind(statement, args);
                try (ResultSet resultSet = statement.executeQuery()) {
                    List<DbRow> rows = new ArrayList<>();
                    ResultSetMetaData meta = resultSet.getMetaData();
                    while (resultSet.next()) {
                        Map<String, Object> values = new LinkedHashMap<>();
                        for (int index = 1; index <= meta.getColumnCount(); index++) {
                            values.put(meta.getColumnLabel(index), resultSet.getObject(index));
                        }
                        rows.add(new DbRow(values));
                    }
                    return rows;
                }
            } catch (SQLException exception) {
                throw new IllegalStateException(exception);
            }
        }

        @Override
        public Optional<DbRow> queryOne(String sql, Object... args) {
            List<DbRow> rows = query(sql, args);
            return rows.isEmpty() ? Optional.empty() : Optional.of(rows.get(0));
        }

        @Override
        public <T> T transaction(Supplier<T> work) {
            return work.get();
        }

        private static void bind(PreparedStatement statement, Object[] args) throws SQLException {
            for (int index = 0; index < args.length; index++) {
                statement.setObject(index + 1, args[index]);
            }
        }
    }
}
