import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** QQ 邮箱绑定的真实 SQL 回归测试（H2 内存库）。 */
class QqEmailBindingServiceTest {

    private static final Pattern TOKEN = Pattern.compile("token=([A-Za-z0-9_-]+)");

    private Connection connection;
    private CapturingMailer mailer;
    private QqEmailBindingService service;

    @BeforeEach
    void setUp() throws SQLException {
        JdbcDataSource dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:qq-email-binding-test;DB_CLOSE_DELAY=-1");
        connection = dataSource.getConnection();
        try (Statement statement = connection.createStatement()) {
            statement.execute("CREATE TABLE IF NOT EXISTS wiki_qq_email_binding ("
                    + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + "user_id BIGINT NOT NULL,"
                    + "qq VARCHAR(20) NOT NULL,"
                    + "token_hash VARCHAR(128) NOT NULL,"
                    + "expires_at TIMESTAMP NOT NULL,"
                    + "verified_at TIMESTAMP,"
                    + "created_at TIMESTAMP NOT NULL)");
            statement.execute("DELETE FROM wiki_qq_email_binding");
        }
        mailer = new CapturingMailer();
        service = new QqEmailBindingService(new TestDatabase(connection), mailer,
                new TestSiteConfig("测试维基"));
    }

    @AfterEach
    void tearDown() throws SQLException {
        if (connection != null) {
            connection.close();
        }
    }

    @Test
    void numericQqGetsEmailAndOneTimeTokenBindsOnlyTheRequestingUser() {
        service.request(7L, "Alice", " 123456789 ", "https://wiki.example.com");

        assertEquals("123456789@qq.com", mailer.to, "必须发到数字 QQ 对应的 QQ 邮箱");
        assertTrue(mailer.subject.contains("测试维基"));
        String token = token(mailer.text);
        assertTrue(service.status(7L).isEmpty());

        assertEquals(QqEmailBindingService.ConfirmResult.WRONG_USER,
                service.confirm(8L, token), "其他账号不能确认别人的 token");
        assertEquals(QqEmailBindingService.ConfirmResult.OK, service.confirm(7L, token));
        assertEquals("123456789", service.status(7L).orElseThrow().qq());

        assertEquals(QqEmailBindingService.ConfirmResult.INVALID,
                service.confirm(7L, token), "token 只能使用一次");
        IllegalArgumentException alreadyBound = assertThrows(IllegalArgumentException.class,
                () -> service.request(7L, "Alice", "123456789", "https://wiki.example.com"));
        assertEquals("qqEmail.alreadyBound", alreadyBound.getMessage());

        IllegalArgumentException taken = assertThrows(IllegalArgumentException.class,
                () -> service.request(8L, "Bob", "123456789", "https://wiki.example.com"));
        assertEquals("qqEmail.qqTaken", taken.getMessage());

        assertTrue(service.unbind(7L));
        assertTrue(service.status(7L).isEmpty());
    }

    @Test
    void pendingQqCannotBeClaimedByAnotherAccount() {
        service.request(7L, "Alice", "123456789", "https://wiki.example.com");
        String firstToken = token(mailer.text);

        IllegalArgumentException pending = assertThrows(IllegalArgumentException.class,
                () -> service.request(8L, "Bob", "123456789", "https://wiki.example.com"));
        assertEquals("qqEmail.qqPending", pending.getMessage());

        // 原地重发：同一账号可以覆盖自己的待确认 token，旧链接立即失效。
        service.request(7L, "Alice", "123456789", "https://wiki.example.com");
        String secondToken = token(mailer.text);
        assertFalse(firstToken.equals(secondToken));
        assertEquals(QqEmailBindingService.ConfirmResult.INVALID, service.confirm(7L, firstToken));
        assertEquals(QqEmailBindingService.ConfirmResult.OK, service.confirm(7L, secondToken));
    }

    @Test
    void invalidQqAndMailFailureDoNotLeaveBindings() throws SQLException {
        assertThrows(IllegalArgumentException.class, () -> service.request(
                7L, "Alice", "alice@qq.com", "https://wiki.example.com"));
        assertThrows(IllegalArgumentException.class, () -> service.request(
                7L, "Alice", "0123456", "https://wiki.example.com"));
        assertThrows(IllegalArgumentException.class, () -> service.request(
                7L, "Alice", "1234", "https://wiki.example.com"));

        mailer.send = false;
        IllegalArgumentException failed = assertThrows(IllegalArgumentException.class,
                () -> service.request(7L, "Alice", "123456789", "https://wiki.example.com"));
        assertEquals("qqEmail.sendFailed", failed.getMessage());
        assertTrue(service.status(7L).isEmpty());
        assertTrue(query("SELECT * FROM wiki_qq_email_binding").isEmpty(),
                "发送失败不能留下待确认记录");
    }

    @Test
    void expiredTokenCannotBind() throws SQLException {
        service.request(7L, "Alice", "123456789", "https://wiki.example.com");
        String token = token(mailer.text);
        try (PreparedStatement statement = connection.prepareStatement(
                "UPDATE wiki_qq_email_binding SET expires_at = ?")) {
            statement.setObject(1, LocalDateTime.now().minusMinutes(1));
            statement.executeUpdate();
        }
        assertEquals(QqEmailBindingService.ConfirmResult.EXPIRED, service.confirm(7L, token));
        assertTrue(service.status(7L).isEmpty());
    }

    private static String token(String text) {
        Matcher matcher = TOKEN.matcher(text);
        assertTrue(matcher.find(), "邮件里应包含确认 token");
        return matcher.group(1);
    }

    private List<DbRow> query(String sql, Object... args) throws SQLException {
        List<DbRow> rows = new ArrayList<>();
        try (PreparedStatement statement = connection.prepareStatement(sql)) {
            bind(statement, args);
            try (ResultSet resultSet = statement.executeQuery()) {
                ResultSetMetaData meta = resultSet.getMetaData();
                int columns = meta.getColumnCount();
                while (resultSet.next()) {
                    Map<String, Object> values = new LinkedHashMap<>();
                    for (int index = 1; index <= columns; index++) {
                        values.put(meta.getColumnLabel(index), resultSet.getObject(index));
                    }
                    rows.add(new DbRow(values));
                }
            }
        }
        return rows;
    }

    private static void bind(PreparedStatement statement, Object... args) throws SQLException {
        for (int index = 0; index < args.length; index++) {
            statement.setObject(index + 1, args[index]);
        }
    }

    private static final class CapturingMailer implements Mailer {
        private boolean send = true;
        private String to;
        private String subject;
        private String text;

        @Override
        public boolean isConfigured() {
            return true;
        }

        @Override
        public boolean isEnabled(String typeId) {
            return true;
        }

        @Override
        public boolean trySend(String typeId, String to, String subject, String text) {
            if (!send) {
                return false;
            }
            this.to = to;
            this.subject = subject;
            this.text = text;
            return true;
        }
    }

    private record TestSiteConfig(String siteName) implements SiteConfig {
        @Override
        public String get(String key, String defaultValue) {
            return "site.name".equals(key) ? siteName : defaultValue;
        }

        @Override
        public boolean getBoolean(String key, boolean defaultValue) {
            return defaultValue;
        }
    }

    /** 测试替身：只实现服务用到的裸 SQL 方法。 */
    private record TestDatabase(Connection connection) implements PluginDatabase {

        @Override
        public String databaseProductName() {
            return "H2";
        }

        @Override
        public List<String> tableNames() {
            return List.of("wiki_qq_email_binding");
        }

        @Override
        public int update(String sql, Object... args) {
            try (PreparedStatement statement = connection.prepareStatement(sql)) {
                bind(statement, args);
                return statement.executeUpdate();
            } catch (SQLException exception) {
                throw new IllegalStateException(exception);
            }
        }

        @Override
        public long insert(String sql, Object... args) {
            throw new UnsupportedOperationException("测试只用 update");
        }

        @Override
        public List<DbRow> query(String sql, Object... args) {
            try {
                List<DbRow> rows = new ArrayList<>();
                try (PreparedStatement statement = connection.prepareStatement(sql)) {
                    bind(statement, args);
                    try (ResultSet resultSet = statement.executeQuery()) {
                        ResultSetMetaData meta = resultSet.getMetaData();
                        int columns = meta.getColumnCount();
                        while (resultSet.next()) {
                            Map<String, Object> values = new LinkedHashMap<>();
                            for (int index = 1; index <= columns; index++) {
                                values.put(meta.getColumnLabel(index), resultSet.getObject(index));
                            }
                            rows.add(new DbRow(values));
                        }
                    }
                }
                return rows;
            } catch (SQLException exception) {
                throw new IllegalStateException(exception);
            }
        }

        @Override
        public Optional<DbRow> queryOne(String sql, Object... args) {
            List<DbRow> rows = query(sql, args);
            return rows.isEmpty() ? Optional.empty() : Optional.of(rows.get(0));
        }

        @Override
        public <T> T transaction(Supplier<T> work) {
            return work.get();
        }
    }
}
