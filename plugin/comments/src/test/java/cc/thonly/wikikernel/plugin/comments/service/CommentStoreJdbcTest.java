package cc.thonly.wikikernel.plugin.comments.service;

import cc.thonly.wikikernel.common.service.DbRow;
import cc.thonly.wikikernel.common.service.PluginDatabase;
import cc.thonly.wikikernel.plugin.comments.data.WikiComment;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.ResultSetMetaData;
import java.sql.SQLException;
import java.sql.Statement;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.function.Supplier;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * {@link CommentStoreJdbc} 的真实 SQL 回归测试（H2 内存库）：
 * 插件自有表 {@code wiki_comment} 的建表语句、列名映射与读写路径都在真数据库上跑一遍
 * （插件测试里的 {@code CommentSectionTest} 用内存替身，覆盖不到 SQL）。
 * <p>
 * 依赖只用 JDBC（测试里自带一个极简的 {@link PluginDatabase} 实现），不需要 core 的 Spring 环境。
 */
class CommentStoreJdbcTest {

    private Connection connection;
    private CommentStoreJdbc store;

    @BeforeEach
    void setUp() throws SQLException {
        JdbcDataSource dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:comment-store-test;DB_CLOSE_DELAY=-1");
        connection = dataSource.getConnection();
        createSchema(connection);
        try (Statement statement = connection.createStatement()) {
            statement.execute("DELETE FROM wiki_comment");
        }
        store = new CommentStoreJdbc(new TestDatabase(connection));
    }

    /** 表结构 = 插件 {@code schemaEntities()} 声明的 {@code wiki_comment}（H2 方言）。 */
    private static void createSchema(Connection connection) throws SQLException {
        execute(connection, "CREATE TABLE IF NOT EXISTS wiki_comment ("
                + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                + "page_title VARCHAR(255) NOT NULL, parent_id BIGINT, user_id BIGINT, content TEXT,"
                + "deleted BOOLEAN DEFAULT 0, deleted_by BIGINT, deleted_at TIMESTAMP, create_at TIMESTAMP NOT NULL)");
    }

    private static void execute(Connection connection, String sql) throws SQLException {
        try (Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    @Test
    void commentRoundTripKeepsOrderAndSoftDelete() {
        String page = "评论桥测试页";
        WikiComment first = comment(page, null, 7L, "第一条");
        store.insert(first);
        assertTrue(first.getId() > 0, "insert 应回填自增主键");
        assertEquals(1, store.count(page));

        WikiComment reply = comment(page, first.getId(), 8L, "回复");
        store.insert(reply);

        List<WikiComment> rows = store.list(page);
        assertEquals(List.of("第一条", "回复"), rows.stream().map(WikiComment::getContent).toList(),
                "按 id 升序（发表时间顺序）");
        assertEquals(2, store.count(page));
        assertEquals(page, store.find(reply.getId()).orElseThrow().getPageTitle());
        assertEquals(first.getId(), store.find(reply.getId()).orElseThrow().getParentId());

        // 软删除：列表里仍是占位（含已删除），计数不含已删除
        reply.setDeleted(true);
        reply.setDeletedBy(9L);
        reply.setDeletedAt(LocalDateTime.now().withNano(0));
        store.update(reply);
        WikiComment deleted = store.find(reply.getId()).orElseThrow();
        assertTrue(deleted.getDeleted());
        assertEquals(9L, deleted.getDeletedBy());
        assertEquals(1, store.count(page));
        assertEquals(2, store.list(page).size());

        // 只更新非 null 字段：只改内容时其它列不动
        WikiComment onlyContent = new WikiComment();
        onlyContent.setId(first.getId());
        onlyContent.setContent("第一条（改过）");
        store.update(onlyContent);
        WikiComment reloaded = store.find(first.getId()).orElseThrow();
        assertEquals("第一条（改过）", reloaded.getContent());
        assertEquals(page, reloaded.getPageTitle(), "没传的字段不动");
        assertEquals(7L, reloaded.getUserId());
        assertFalse(reloaded.getDeleted());
        assertNull(reloaded.getDeletedAt());
    }

    @Test
    void blankTitlesAndMissingRowsReturnEmptyResults() {
        assertTrue(store.list("").isEmpty());
        assertTrue(store.list("   ").isEmpty());
        assertEquals(0, store.count(null));
        assertEquals(0, store.count("不存在的页面"));
        assertTrue(store.find(999_999L).isEmpty());
    }

    @Test
    void countOnlyCountsTheGivenPage() {
        store.insert(comment("页面甲", null, 1L, "甲一"));
        store.insert(comment("页面甲", null, 1L, "甲二"));
        store.insert(comment("页面乙", null, 2L, "乙一"));

        assertEquals(2, store.count("页面甲"));
        assertEquals(1, store.count("页面乙"));
        assertEquals(2, store.list("页面甲").size());
    }

    // ==================== 测试替身 ====================

    private static WikiComment comment(String page, Long parentId, Long userId, String content) {
        WikiComment comment = new WikiComment();
        comment.setPageTitle(page);
        comment.setParentId(parentId);
        comment.setUserId(userId);
        comment.setContent(content);
        comment.setDeleted(false);
        comment.setCreateAt(LocalDateTime.now().withNano(0));
        return comment;
    }

    /** 极简 JDBC 版 {@link PluginDatabase}（生产实现是 core 的 PluginDatabaseImpl）。 */
    private record TestDatabase(Connection connection) implements PluginDatabase {

        @Override
        public String databaseProductName() {
            return "SQLite";
        }

        @Override
        public List<String> tableNames() {
            return List.of();
        }

        @Override
        public int update(String sql, Object... args) {
            try (PreparedStatement statement = connection.prepareStatement(sql)) {
                bind(statement, args);
                return statement.executeUpdate();
            } catch (SQLException exception) {
                throw new IllegalStateException(exception);
            }
        }

        @Override
        public long insert(String sql, Object... args) {
            try (PreparedStatement statement = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
                bind(statement, args);
                statement.executeUpdate();
                try (ResultSet keys = statement.getGeneratedKeys()) {
                    return keys.next() ? keys.getLong(1) : -1;
                }
            } catch (SQLException exception) {
                throw new IllegalStateException(exception);
            }
        }

        @Override
        public List<DbRow> query(String sql, Object... args) {
            try (PreparedStatement statement = connection.prepareStatement(sql)) {
                bind(statement, args);
                try (ResultSet resultSet = statement.executeQuery()) {
                    List<DbRow> rows = new ArrayList<>();
                    ResultSetMetaData meta = resultSet.getMetaData();
                    while (resultSet.next()) {
                        Map<String, Object> values = new LinkedHashMap<>();
                        for (int index = 1; index <= meta.getColumnCount(); index++) {
                            values.put(meta.getColumnLabel(index), resultSet.getObject(index));
                        }
                        rows.add(new DbRow(values));
                    }
                    return rows;
                }
            } catch (SQLException exception) {
                throw new IllegalStateException(exception);
            }
        }

        @Override
        public Optional<DbRow> queryOne(String sql, Object... args) {
            List<DbRow> rows = query(sql, args);
            return rows.isEmpty() ? Optional.empty() : Optional.of(rows.get(0));
        }

        @Override
        public <T> T transaction(Supplier<T> work) {
            return work.get();
        }

        private static void bind(PreparedStatement statement, Object[] args) throws SQLException {
            for (int index = 0; index < args.length; index++) {
                statement.setObject(index + 1, args[index]);
            }
        }
    }
}
